#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
m3b_inject_trap_include.py - M3b (swe_native_3d_v2): make the recompiled tree
self-consistent for the apply_*.py chain.

Two things the v2 tree (regenerated from scratch) lacks and the v1 tree has:

1. `#include "nd_indirect_trap.h"` in every TU.  The chain emits calls to the
   helpers declared there (`neverdead_epilogue_822CACC0`, ...).  In v1 the
   include was injected by the predecessor with the temporary
   `apply_indirect_trap.py`, which globs the TUs in the PROJECT ROOT (the layout
   of that time) and is explicitly "SIN target CMake".

2. The declaration of the functions the chain calls ACROSS translation units.
   The codegen only declares a function in the module header of the module
   that DEFINES it and in the module headers of the modules that CALL it
   (verified: neverdead_funcs.42.h does not declare sub_822081E0, whose
   definition lives in recomp.29.cpp).  A chain patch that turns a
   REX_FATAL into `sub_X(ctx, base);` introduces a call the module header does
   not know about => "use of undeclared identifier 'sub_X'".

This script therefore
  * injects `#include "nd_indirect_trap.h"` and `#include "nd_chain_decls.h"`
    after the module header include of every TU, and
  * generates `nd_chain_decls.h` in the tree with the DECLARE_REX_FUNC of every
    function that a TU calls but its own module header does not declare
    (excluding the ones already declared by src/nd_indirect_trap.h, which are
    plain C++ functions and would clash with DECLARE_REX_FUNC).

Idempotent: a second run rewrites nothing.

Usage
-----
    python tools/m3b_inject_trap_include.py [--project-root DIR] [--check]
"""
from __future__ import annotations

import argparse
import glob
import os
import re
import sys
from pathlib import Path

INCLUDE_TRAP = '#include "nd_indirect_trap.h"'
INCLUDE_DECLS = '#include "nd_chain_decls.h"'
DECLS_NAME = "nd_chain_decls.h"
ANCHOR_RE = re.compile(r'(?m)^[ \t]*#include "neverdead_funcs\.\d+\.h"[^\r\n]*\r?\n')
MODULE_RE = re.compile(r'#include "neverdead_funcs\.(\d+)\.h"')
CALL_RE = re.compile(r"\b(sub_[0-9A-Fa-f]{8})\s*\(\s*ctx\s*,")
DECL_RE = re.compile(r"DECLARE_REX_FUNC\(\s*(sub_[0-9A-Fa-f]{8})\s*\)")
REL_GLOB = "neverdead_recomp.*.cpp"


def gen_dir(root: Path) -> Path:
    override = os.environ.get("NEVERDEAD_GENERATED_DIR")
    if override:
        p = Path(override)
        return p if p.is_absolute() else Path(root) / p
    return Path(root) / "generated" / "neverdead_default"


def _read(p: Path) -> str:
    with p.open("r", encoding="utf-8", newline="") as fp:
        return fp.read()


def _write_atomic(p: Path, text: str) -> None:
    tmp = p.with_suffix(p.suffix + ".tmp")
    with tmp.open("w", encoding="utf-8", newline="") as fp:
        fp.write(text)
    os.replace(tmp, p)


def _eol(text: str) -> str:
    return "\r\n" if "\r\n" in text else "\n"


def _strip_line_comment(line: str) -> str:
    in_str = False
    i = 0
    while i < len(line) - 1:
        c = line[i]
        if c == '"' and (i == 0 or line[i - 1] != "\\"):
            in_str = not in_str
        elif not in_str and c == "/" and line[i + 1] == "/":
            return line[:i]
        i += 1
    return line


def collect_missing_decls(gd: Path, trap_header: Path) -> list[str]:
    """Functions called by a TU whose own module header does not declare them."""
    trap_text = trap_header.read_text(encoding="utf-8", errors="replace") if trap_header.is_file() else ""
    trap_subs = set(re.findall(r"\bsub_[0-9A-Fa-f]{8}\b", trap_text))
    missing: set[str] = set()
    for p in sorted(Path(gd).glob(REL_GLOB)):
        text = _read(p)
        m = MODULE_RE.search(text)
        if not m:
            continue
        hdr = gd / f"neverdead_funcs.{m.group(1)}.h"
        declared = set()
        if hdr.is_file():
            declared = set(DECL_RE.findall(_read(hdr)))
        for line in text.splitlines():
            code = _strip_line_comment(line)
            for name in CALL_RE.findall(code):
                if name in declared or name in trap_subs:
                    continue
                missing.add(name)
    return sorted(missing)


def write_decls(gd: Path, names: list[str]) -> None:
    lines = [
        "// nd_chain_decls.h - GENERATED by tools/m3b_inject_trap_include.py (M3b).",
        "// DO NOT EDIT: declarations of the functions that the apply_*.py chain",
        "// calls across translation units (the codegen only declares a function",
        "// in the module header of its own module).",
        "#pragma once",
        "",
        "#include \"neverdead_pch.h\"",
        "",
    ]
    for n in names:
        lines.append(f"DECLARE_REX_FUNC({n});")
    lines.append("")
    _write_atomic(gd / DECLS_NAME, "\n".join(lines))


def process(path: Path, check: bool) -> str:
    text = _read(path)
    if INCLUDE_TRAP in text and INCLUDE_DECLS in text:
        return "clean"
    m = ANCHOR_RE.search(text)
    if not m:
        return "no-anchor"
    if not check:
        eol = _eol(text)
        ins = ""
        if INCLUDE_TRAP not in text:
            ins += INCLUDE_TRAP + eol
        if INCLUDE_DECLS not in text:
            ins += INCLUDE_DECLS + eol
        text = text[: m.end()] + ins + text[m.end():]
        _write_atomic(path, text)
    return "patched"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--project-root", type=Path, default=Path(__file__).resolve().parents[1])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    root = args.project_root
    gd = gen_dir(root)
    files = sorted(Path(p) for p in glob.glob(str(gd / REL_GLOB)))
    if not files:
        print(f"ERROR: no TUs under {gd}", file=sys.stderr)
        return 2
    trap_header = root / "src" / "nd_indirect_trap.h"
    missing = collect_missing_decls(gd, trap_header)
    if not args.check:
        write_decls(gd, missing)
    counts: dict[str, int] = {}
    for p in files:
        r = process(p, args.check)
        counts[r] = counts.get(r, 0) + 1
    print(f"PATCH(neverdead-trap-include): {counts} ({gd}); "
          f"{len(missing)} cross-module declaration(s) in {DECLS_NAME}")
    if missing and args.check:
        print("  missing: " + ", ".join(missing))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
