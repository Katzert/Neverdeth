#!/usr/bin/env python3
"""
Register ALL code pointers found anywhere in .rdata into config/vtables.toml.
Ensures zero unregistered vtable slots or callbacks exist in .rdata.
"""
import struct
import re
from pathlib import Path

def main():
    root = Path(__file__).resolve().parent.parent
    base_exe = root / "NeverDead_base.exe"
    init_cpp = root / "generated" / "neverdead_default" / "neverdead_init.cpp"
    out_toml = root / "config" / "vtables.toml"

    with open(base_exe, "rb") as f:
        flat = f.read()

    registered = set()
    if init_cpp.exists():
        with open(init_cpp, "r", encoding="utf-8") as f:
            registered = set(int(x, 16) for x in re.findall(r"\{\s*(0x[0-9A-Fa-f]+),", f.read()))

    # Parse .pdata
    pdata_raw = flat[0x16F800:0x16F800+0x238D0]
    pdata = []
    for va, flags in struct.iter_unpack(">II", pdata_raw):
        if 0x821A0000 <= va < 0x827C05E4 and va % 4 == 0:
            pdata.append((va, flags))
    pdata.sort(key=lambda x: x[0])

    rdata = flat[0x600:0x16F680]
    code_min = 0x821A0000
    code_max = 0x827C05E4

    all_code_ptrs = set()
    for i in range(0, len(rdata), 4):
        val = struct.unpack_from(">I", rdata, i)[0]
        if code_min <= val < code_max and val % 4 == 0:
            all_code_ptrs.add(val)

    missing = sorted([s for s in all_code_ptrs if s not in registered])
    print(f"Total unregistered code pointers in .rdata: {len(missing)}")

    # Read existing entries from vtables.toml so we don't drop any
    existing_entries = {}
    if out_toml.exists():
        cur_addr = None
        cur_p = None
        cur_e = None
        cur_name = None
        with open(out_toml, "r", encoding="utf-8") as f:
            for line in f:
                m = re.match(r'\[functions\."(0x[0-9A-Fa-f]+)"\]', line)
                if m:
                    if cur_addr:
                        existing_entries[cur_addr] = (cur_p, cur_e, cur_name)
                    cur_addr = int(m.group(1), 16)
                    cur_p = None
                    cur_e = None
                    cur_name = None
                m_p = re.match(r'parent\s*=\s*(\d+)', line)
                if m_p:
                    cur_p = int(m_p.group(1))
                m_e = re.match(r'end\s*=\s*(\d+)', line)
                if m_e:
                    cur_e = int(m_e.group(1))
                m_n = re.match(r'name\s*=\s*"([^"]+)"', line)
                if m_n:
                    cur_name = m_n.group(1)
            if cur_addr:
                existing_entries[cur_addr] = (cur_p, cur_e, cur_name)

    print(f"Existing entries in vtables.toml: {len(existing_entries)}")

    # Add missing
    added = 0
    for m in missing:
        if m in existing_entries:
            continue
        # Find owner in pdata
        found = False
        for i in range(len(pdata) - 1):
            start = pdata[i][0]
            next_start = pdata[i+1][0]
            if start <= m < next_start:
                existing_entries[m] = (start, next_start, f"vtable_slot_{m:08X}")
                found = True
                added += 1
                break
        if not found and pdata[-1][0] <= m < code_max:
            existing_entries[m] = (pdata[-1][0], code_max, f"vtable_slot_{m:08X}")
            added += 1

    print(f"Newly added entries: {added}, Total in vtables.toml: {len(existing_entries)}")

    header = """# config/vtables.toml - Exhaustive registration of all .rdata code pointers
# Generated by tools/register_all_rdata_ptrs.py

"""
    lines = [header]
    for addr in sorted(existing_entries.keys()):
        parent, end, name = existing_entries[addr]
        lines.append(f'[functions."0x{addr:08X}"]\n')
        lines.append(f'parent = {parent}\n')
        lines.append(f'end = {end}\n')
        lines.append(f'name = "{name}"\n\n')

    with open(out_toml, "w", encoding="utf-8") as f:
        f.writelines(lines)

    print(f"Wrote {len(existing_entries)} entries to {out_toml}")

if __name__ == "__main__":
    main()
