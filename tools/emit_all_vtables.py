#!/usr/bin/env python3
"""
Emit all missing vtable slot functions into config/vtables.toml.
Derived from full scan of .rdata vtables against NeverDead_base.exe and .pdata.
"""
import struct
import re
from pathlib import Path

def main():
    root = Path(__file__).resolve().parent.parent
    base_exe = root / "NeverDead_base.exe"
    init_cpp = root / "generated" / "neverdead_default" / "neverdead_init.cpp"
    out_toml = root / "config" / "vtables.toml"

    with open(base_exe, "rb") as f:
        flat = f.read()

    registered = set()
    if init_cpp.exists():
        with open(init_cpp, "r", encoding="utf-8") as f:
            registered = set(int(x, 16) for x in re.findall(r"\{\s*(0x[0-9A-Fa-f]+),", f.read()))

    # Parse .pdata
    pdata_raw = flat[0x16F800:0x16F800+0x238D0]
    pdata = []
    for va, flags in struct.iter_unpack(">II", pdata_raw):
        if 0x821A0000 <= va < 0x827C05E4 and va % 4 == 0:
            pdata.append((va, flags))
    pdata.sort(key=lambda x: x[0])

    # Scan .rdata for candidate vtables
    rdata = flat[0x600:0x16F680]
    code_min = 0x821A0000
    code_max = 0x827C05E4

    tables = []
    current_table = []
    for i in range(0, len(rdata), 4):
        va = 0x82000600 + i
        val = struct.unpack_from(">I", rdata, i)[0]
        if code_min <= val < code_max and val % 4 == 0:
            current_table.append((va, val))
        else:
            if len(current_table) >= 2:
                tables.append(current_table)
            current_table = []
    if len(current_table) >= 2:
        tables.append(current_table)

    all_slots = set()
    for t in tables:
        for s_va, target in t:
            all_slots.add(target)

    # Missing slots (not currently registered)
    missing = sorted([s for s in all_slots if s not in registered])
    print(f"Total missing vtable slot targets: {len(missing)}")

    # Map to parent/end
    entries = []
    for m in missing:
        found = False
        for i in range(len(pdata) - 1):
            start = pdata[i][0]
            next_start = pdata[i+1][0]
            if start <= m < next_start:
                entries.append((m, start, next_start))
                found = True
                break
        if not found and pdata[-1][0] <= m < code_max:
            entries.append((m, pdata[-1][0], code_max))

    header = """# config/vtables.toml - Exhaustive census of vtable slots from .rdata
# Generated by tools/emit_all_vtables.py

"""
    lines = [header]
    for m, parent, end in entries:
        lines.append(f'[functions."0x{m:08X}"]\n')
        lines.append(f'parent = {parent}\n')
        lines.append(f'end = {end}\n')
        lines.append(f'name = "vtable_slot_{m:08X}"\n\n')

    with open(out_toml, "w", encoding="utf-8") as f:
        f.writelines(lines)

    print(f"Wrote {len(entries)} vtable slot entries to {out_toml}")

if __name__ == "__main__":
    main()
